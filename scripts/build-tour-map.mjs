#!/usr/bin/env node
/**
 * Build the Western Visayas outline drawn by the Lab Tour's Variant tree map
 * (lib/tour-map-shapes.ts) from a province GeoJSON.
 *
 * Source: faeldon/philippines-json-maps (MIT), 2023 PSGC, low resolution:
 *   https://raw.githubusercontent.com/faeldon/philippines-json-maps/master/2023/geojson/regions/lowres/provdists-region-600000000.0.001.json
 *
 * Coordinates are projected equirectangularly (longitude scaled by the cosine
 * of the mid latitude), islets under --min-area km² are dropped, and each
 * province gets an anchor at the area-weighted centre of its largest polygon.
 *
 * Usage:
 *   node scripts/build-tour-map.mjs <region.geojson> [lib/tour-map-shapes.ts] [--min-area 4]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const WIDTH = 400;
const PAD = 8;
const KM_PER_DEG = 111.32;

/** Signed shoelace area and centroid of one ring, in the ring's own units. */
function ringStats(ring) {
  let a = 0;
  let cx = 0;
  let cy = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [x0, y0] = ring[j];
    const [x1, y1] = ring[i];
    const cross = x0 * y1 - x1 * y0;
    a += cross;
    cx += (x0 + x1) * cross;
    cy += (y0 + y1) * cross;
  }
  a /= 2;
  return { area: a, cx: a ? cx / (6 * a) : ring[0][0], cy: a ? cy / (6 * a) : ring[0][1] };
}

export function buildTourMap(geojson, { minAreaKm2 = 4 } = {}) {
  const features = geojson.features.map((f) => ({
    name: f.properties.adm2_en,
    polygons: f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates,
  }));

  let minLon = Infinity;
  let maxLon = -Infinity;
  let minLat = Infinity;
  let maxLat = -Infinity;
  for (const f of features) {
    for (const poly of f.polygons) {
      for (const [lon, lat] of poly[0]) {
        minLon = Math.min(minLon, lon);
        maxLon = Math.max(maxLon, lon);
        minLat = Math.min(minLat, lat);
        maxLat = Math.max(maxLat, lat);
      }
    }
  }
  const k = Math.cos((((minLat + maxLat) / 2) * Math.PI) / 180);
  const scale = (WIDTH - 2 * PAD) / ((maxLon - minLon) * k);
  const height = Math.round((maxLat - minLat) * scale + 2 * PAD);
  const project = ([lon, lat]) => [PAD + (lon - minLon) * k * scale, PAD + (maxLat - lat) * scale];
  const kmPerUnit = KM_PER_DEG / scale;
  const r1 = (n) => Math.round(n * 10) / 10;

  const provinces = features.map((f) => {
    let best = null;
    const parts = [];
    for (const poly of f.polygons) {
      const rings = poly.map((ring) => ring.map(project));
      const outer = ringStats(rings[0]);
      if (Math.abs(outer.area) * kmPerUnit * kmPerUnit < minAreaKm2) continue;
      if (!best || Math.abs(outer.area) > Math.abs(best.area)) best = outer;
      for (const ring of rings) {
        const pts = ring.map(([x, y]) => [r1(x), r1(y)]);
        const deduped = pts.filter((p, i) => i === 0 || p[0] !== pts[i - 1][0] || p[1] !== pts[i - 1][1]);
        if (deduped.length < 4) continue;
        parts.push(`M${deduped.slice(0, -1).map((p) => p.join(",")).join("L")}Z`);
      }
    }
    return { name: f.name, path: parts.join(""), anchor: [r1(best.cx), r1(best.cy)] };
  });

  return { width: WIDTH, height, provinces };
}

function main(argv) {
  const args = argv.filter((a, i) => !a.startsWith("--") && argv[i - 1] !== "--min-area");
  const [input, output = "lib/tour-map-shapes.ts"] = args;
  const minIdx = argv.indexOf("--min-area");
  const minAreaKm2 = minIdx >= 0 ? Number(argv[minIdx + 1]) : 4;
  if (!input || !Number.isFinite(minAreaKm2)) {
    console.error("Usage: node scripts/build-tour-map.mjs <region.geojson> [out.ts] [--min-area 4]");
    process.exit(1);
  }
  const map = buildTourMap(JSON.parse(readFileSync(input, "utf8")), { minAreaKm2 });
  const body = `/**
 * Western Visayas province outlines for the Lab Tour's Variant tree map.
 * Generated by scripts/build-tour-map.mjs from faeldon/philippines-json-maps
 * (MIT, 2023 PSGC, low resolution) — do not edit by hand.
 */

export type TourMapProvince = { name: string; path: string; anchor: [x: number, y: number] };

export const TOUR_MAP: { width: number; height: number; provinces: TourMapProvince[] } = ${JSON.stringify(map, null, 2)};
`;
  writeFileSync(output, body);
  // eslint-disable-next-line no-console -- CLI output
  console.log(`Wrote ${output} (${(Buffer.byteLength(body) / 1024).toFixed(0)} KB), ${map.width}×${map.height}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}
